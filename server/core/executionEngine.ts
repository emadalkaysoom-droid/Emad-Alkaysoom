export function executeSandboxedJavaScript(code: string): { result: unknown; logs: string[]; durationMs: number } {
  const start = performance.now();
  const logs: string[] = [];
  const sandbox = {
    Math,
    JSON,
    Number,
    String,
    Array,
    Object,
    Date,
    console: {
      log: (...args: unknown[]) => logs.push(args.map((a) => String(a)).join(' ')),
    },
  };
  const context = vm.createContext(sandbox, {
    codeGeneration: { strings: false, wasm: false },
  });
  const script = new vm.Script(`(() => {\n${code}\n})()`);
  const result = script.runInContext(context, { timeout: 500 });
  return {
    result,
    logs,
    durationMs: Math.round(performance.now() - start),
  };
}

export function parseFileRows(params: {
  fileName: string;
  mimeType: string;
  contentText?: string;
  base64Buffer?: string;
}): DataRow[] {
  const lower = params.fileName.toLowerCase();
  if (lower.endsWith('.xlsx') || lower.endsWith('.xls') || params.mimeType.includes('spreadsheet')) {
    if (!params.base64Buffer) {
      throw new Error('XLSX parsing requires base64 binary payload');
    }
    const buf = Buffer.from(params.base64Buffer, 'base64');
    const wb = XLSX.read(buf, { type: 'buffer' });
    const firstSheet = wb.SheetNames[0];
    if (!firstSheet) return [];
    return XLSX.utils.sheet_to_json<DataRow>(wb.Sheets[firstSheet], { defval: null });
  }

  const text = params.contentText || '';
  if (lower.endsWith('.json') || params.mimeType.includes('json')) {
    return parseStructuredText(text, 'json');
  }
  if (lower.endsWith('.xml') || params.mimeType.includes('xml')) {
    return parseStructuredText(text, 'xml');
  }
  return parseStructuredText(text, 'csv');
}

export async function compileReportArtifact(params: {
  workspaceId: string;
  projectId?: string | null;
  title: string;
  format: 'pdf' | 'docx' | 'xlsx' | 'csv' | 'html';
  summary: string;
  sections: Array<{ heading: string; body: string }>;
  tableRows?: DataRow[];
}): Promise<{ reportId: string; fileName: string; mimeType: string; buffer: Buffer }> {
  const db = getDb();
  const reportId = `rep-${crypto.randomUUID().slice(0, 8)}`;
  const safeSlug = params.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 40) || 'omnix-report';

  db.prepare(
    `INSERT INTO reports (id, workspace_id, project_id, title, format, summary, payload_json)
     VALUES (?, ?, ?, ?, ?, ?, ?)`
  ).run(
    reportId,
    params.workspaceId,
    params.projectId ?? null,
    params.title,
    params.format,
    params.summary,
    JSON.stringify({ sections: params.sections, rowCount: params.tableRows?.length ?? 0 })
  );

  if (params.format === 'pdf') {
    const doc = new jsPDF();
    doc.setFontSize(16);
    doc.text(params.title, 14, 20);
    doc.setFontSize(10);
    doc.text(`Generated by OMNIX Report Compiler | ${new Date().toISOString()}`, 14, 28);
    let y = 38;
    const addWrapped = (text: string, size = 10) => {
      doc.setFontSize(size);
      const lines = doc.splitTextToSize(text, 180) as string[];
      for (const line of lines) {
        if (y > 275) {
          doc.addPage();
          y = 20;
        }
        doc.text(line, 14, y);
        y += 6;
      }
    };
    addWrapped(params.summary, 11);
    y += 4;
    for (const sec of params.sections) {
      addWrapped(sec.heading, 13);
      addWrapped(sec.body, 10);
      y += 4;
    }
    const arrayBuf = doc.output('arraybuffer');
    return {
      reportId,
      fileName: `${safeSlug}.pdf`,
      mimeType: 'application/pdf',
      buffer: Buffer.from(arrayBuf),
    };
  }

  if (params.format === 'docx') {
    const children: Paragraph[] = [
      new Paragraph({ text: params.title, heading: HeadingLevel.HEADING_1 }),
      new Paragraph({
        children: [
          new TextRun({ text: `Generated: ${new Date().toISOString()}`, italics: true }),
        ],
      }),
      new Paragraph({ text: params.summary }),
    ];
    for (const sec of params.sections) {
      children.push(new Paragraph({ text: sec.heading, heading: HeadingLevel.HEADING_2 }));
      children.push(new Paragraph({ text: sec.body }));
    }
    const doc = new Document({ sections: [{ children }] });
    const buffer = await Packer.toBuffer(doc);
    return {
      reportId,
      fileName: `${safeSlug}.docx`,
      mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
      buffer,
    };
  }

  if (params.format === 'xlsx') {
    const wb = XLSX.utils.book_new();
    const summarySheet = XLSX.utils.json_to_sheet([
      { Title: params.title, Generated: new Date().toISOString(), Summary: params.summary },
      ...params.sections.map((s) => ({ Title: s.heading, Generated: '', Summary: s.body })),
    ]);
    XLSX.utils.book_append_sheet(wb, summarySheet, 'Summary');
    if (params.tableRows && params.tableRows.length > 0) {
      const dataSheet = XLSX.utils.json_to_sheet(params.tableRows);
      XLSX.utils.book_append_sheet(wb, dataSheet, 'Dataset');
    }
    const out = XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' }) as Buffer;
    return {
      reportId,
      fileName: `${safeSlug}.xlsx`,
      mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
      buffer: out,
    };
  }

  if (params.format === 'csv') {
    const rows = params.tableRows && params.tableRows.length > 0
      ? params.tableRows
      : params.sections.map((s) => ({ Section: s.heading, Content: s.body }));
    const ws = XLSX.utils.json_to_sheet(rows);
    const csv = XLSX.utils.sheet_to_csv(ws);
    return {
      reportId,
      fileName: `${safeSlug}.csv`,
      mimeType: 'text/csv; charset=utf-8',
      buffer: Buffer.from(csv, 'utf8'),
    };
  }

  // HTML
  const escapeHtml = (s: string) =>
    s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>${escapeHtml(params.title)}</title>
<style>
  body { font-family: system-ui, sans-serif; max-width: 900px; margin: 40px auto; padding: 0 24px; color: #0f172a; line-height: 1.6; }
  h1 { border-bottom: 2px solid #e2e8f0; padding-bottom: 12px; }
  .meta { color: #64748b; font-size: 13px; margin-bottom: 24px; }
  section { margin-bottom: 24px; }
</style>
</head>
<body>
  <h1>${escapeHtml(params.title)}</h1>
  <div class="meta">Generated by OMNIX Report Compiler · ${new Date().toISOString()}</div>
  <p>${escapeHtml(params.summary)}</p>
  ${params.sections
    .map((s) => `<section><h2>${escapeHtml(s.heading)}</h2><p>${escapeHtml(s.body)}</p></section>`)
    .join('\n')}
</body>
</html>`;
  return {
    reportId,
    fileName: `${safeSlug}.html`,
    mimeType: 'text/html; charset=utf-8',
    buffer: Buffer.from(html, 'utf8'),
  };
}

export async function runToolAction(
  toolName: string,
  args: Record<string, unknown>,
  context: { workspaceId: string; projectId?: string | null; userId: string }
): Promise<Record<string, unknown>> {
  const db = getDb();

  switch (toolName) {
    case 'math_eval': {
      const expr = String(args.expression || '');
      return { ...evaluateMathExpression(expr) };
    }
    case 'sandbox_js': {
      const code = String(args.code || '');
      return executeSandboxedJavaScript(code);
    }
    case 'analyze_data': {
      let rows: DataRow[] = Array.isArray(args.rows) ? (args.rows as DataRow[]) : [];
      if (rows.length === 0 && args.fileId) {
        const file = db
          .prepare(`SELECT name, mime_type, content_text FROM files WHERE id = ? AND workspace_id = ?`)
          .get(String(args.fileId), context.workspaceId) as
          | { name: string; mime_type: string; content_text: string }
          | undefined;
        if (file) {
          rows = parseFileRows({
            fileName: file.name,
            mimeType: file.mime_type,
            contentText: file.content_text,
          });
        }
      } else if (rows.length === 0) {
        const latestFile = db
          .prepare(
            `SELECT name, mime_type, content_text FROM files WHERE workspace_id = ? ORDER BY created_at DESC LIMIT 1`
          )
          .get(context.workspaceId) as
          | { name: string; mime_type: string; content_text: string }
          | undefined;
        if (latestFile) {
          rows = parseFileRows({
            fileName: latestFile.name,
            mimeType: latestFile.mime_type,
            contentText: latestFile.content_text,
          });
        }
      }
      const analysis = analyzeDataset(rows);
      const nl = args.query
        ? interpretNaturalLanguageDataQuery(String(args.query), rows, analysis)
        : null;
      return { analysis, nl };
    }
    case 'save_memory': {
      const id = `mem-${crypto.randomUUID().slice(0, 8)}`;
      const title = String(args.title || 'Workspace Insight');
      const content = String(args.content || '');
      const scope = args.scope === 'short_term' ? 'short_term' : 'long_term';
      db.prepare(
        `INSERT INTO memory_entries (id, workspace_id, project_id, scope, title, content, source, tags_json)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?)`
      ).run(
        id,
        context.workspaceId,
        context.projectId ?? null,
        scope,
        title,
        content,
        'omni-brain',
        JSON.stringify(Array.isArray(args.tags) ? args.tags : ['automated'])
      );
      return { savedMemoryId: id, title, scope };
    }
    case 'create_3d_blueprint': {
      const prompt = String(args.prompt || 'robotic arm');
      const synthesized = await synthesize3DBlueprint({
        prompt,
        workspaceId: context.workspaceId,
      });
      const blueprint = synthesized.blueprint;
      const id = `3d-${crypto.randomUUID().slice(0, 8)}`;
      db.prepare(
        `INSERT INTO three_d_assets (id, workspace_id, project_id, name, prompt, format, blueprint_json)
         VALUES (?, ?, ?, ?, ?, 'parametric-json', ?)`
      ).run(id, context.workspaceId, context.projectId ?? null, blueprint.title, prompt, JSON.stringify(blueprint));
      return { assetId: id, blueprint, provider: synthesized.provider, model: synthesized.model };
    }
    case 'create_world_blueprint': {
      const prompt = String(args.prompt || 'digital twin city');
      const synthesized = await synthesizeWorldBlueprint({
        prompt,
        workspaceId: context.workspaceId,
      });
      const world = synthesized.world;
      const id = `sim-${crypto.randomUUID().slice(0, 8)}`;
      db.prepare(
        `INSERT INTO simulation_projects (id, workspace_id, project_id, name, sim_type, config_json, results_json)
         VALUES (?, ?, ?, ?, 'digital_world', ?, ?)`
      ).run(id, context.workspaceId, context.projectId ?? null, world.title, JSON.stringify(world), JSON.stringify({ status: 'generated' }));
      return { simulationId: id, world, provider: synthesized.provider, model: synthesized.model };
    }
    case 'memory_search': {
      const q = `%${String(args.query || '')}%`;
      const hits = db
        .prepare(
          `SELECT id, scope, title, content, source, created_at FROM memory_entries
           WHERE workspace_id = ? AND (title LIKE ? OR content LIKE ?)
           ORDER BY created_at DESC LIMIT 6`
        )
        .all(context.workspaceId, q, q);
      return { hits };
    }
    case 'codex_scan': {
      const code = String(args.code || 'export const ok = true;');
      const report = analyzeProjectFiles([{ path: 'snippet.ts', content: code }]);
      return { qualityScore: report.qualityScore, securityScore: report.securityScore, findingsCount: report.findings.length };
    }
    case 'lab_experiment': {
      const phys = runPhysicsExperiment({ experimentType: 'projectile', v0: Number(args.v0 || 30), angleDeg: Number(args.angleDeg || 45) });
      return { metrics: phys.metrics, equations: phys.equations };
    }
    case 'autobuild_app': {
      const bp = buildApplicationBlueprint(String(args.prompt || 'Engineering Portal'));
      return { appName: bp.appName, entities: bp.entities.length, endpoints: bp.endpoints.length, qcPassed: bp.qcReport.passed };
    }
    default:
      throw new Error(`Unknown tool '${toolName}'`);
  }
}
